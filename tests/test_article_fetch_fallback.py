from __future__ import annotations

import unittest
from types import SimpleNamespace
from unittest.mock import patch

import analyzer.article_fetcher as af

URL = "https://www.espn.com/f1/story/_/id/1/camara-haas"
PARAGRAPH = "Rafael Camara will race for Haas next season, ESPN understands, after his F2 title run. " * 3
ESPN_PAGE = (
    "<html><body><article><header><h1>Camara to Haas</h1></header></article>"
    f"<article><div class='article-body'><p>{PARAGRAPH}</p><p>{PARAGRAPH}</p></div></article>"
    "</body></html>"
)
CLOUDFRONT_BLOCK = (
    "<html><body><h1>403 ERROR</h1><h2>The request could not be satisfied.</h2>"
    "<p>Request blocked. We can't connect to the server for this app or website at this time. "
    "There might be too much traffic or a configuration error. Generated by cloudfront (CloudFront).</p>"
    "</body></html>"
)


def _response(status: int, text: str) -> SimpleNamespace:
    def raise_for_status() -> None:
        if status >= 400:
            raise RuntimeError(f"HTTP {status}")
    return SimpleNamespace(status_code=status, text=text, raise_for_status=raise_for_status)


class HtmlFallbackTests(unittest.TestCase):
    def _fetch(self, responses: dict[str, SimpleNamespace]) -> tuple[str | None, list[str]]:
        agents: list[str] = []

        def fake(url, timeout, headers, policy, method):
            agents.append(headers["User-Agent"])
            return responses[headers["User-Agent"]]

        with patch.object(af, "_fetch_following_safe_redirects", side_effect=fake):
            return af._fetch_via_html(URL, 15), agents

    def test_challenged_browser_agent_retries_with_pipeline_agent(self) -> None:
        text, agents = self._fetch({
            af.BROWSER_USER_AGENT: _response(202, ""),
            af.PIPELINE_USER_AGENT: _response(200, ESPN_PAGE),
        })
        self.assertEqual(agents, [af.BROWSER_USER_AGENT, af.PIPELINE_USER_AGENT])
        self.assertIn("Rafael Camara will race for Haas", text)

    def test_browser_agent_success_does_not_refetch(self) -> None:
        text, agents = self._fetch({af.BROWSER_USER_AGENT: _response(200, ESPN_PAGE)})
        self.assertEqual(agents, [af.BROWSER_USER_AGENT])
        self.assertIn("Rafael Camara", text)

    def test_block_page_is_not_returned_as_article(self) -> None:
        text, agents = self._fetch({
            af.BROWSER_USER_AGENT: _response(200, CLOUDFRONT_BLOCK),
            af.PIPELINE_USER_AGENT: _response(200, CLOUDFRONT_BLOCK),
        })
        self.assertIsNone(text)
        self.assertEqual(len(agents), 2)


class ExtractionTests(unittest.TestCase):
    def test_empty_first_article_does_not_hide_the_body(self) -> None:
        self.assertIn("Rafael Camara will race for Haas", af._extract_html_article_body(ESPN_PAGE))

    def test_long_article_mentioning_access_denied_is_not_a_block_page(self) -> None:
        article = "The team was access denied to the paddock after the incident. " * 40
        self.assertFalse(af._looks_blocked(article))
        self.assertTrue(af._looks_blocked("Request blocked. Generated by cloudfront (CloudFront)"))

    def test_jina_block_page_is_rejected(self) -> None:
        body = "Title: ERROR\n\nMarkdown Content:\n" + "Request blocked. We can't connect to the server. " * 5
        response = SimpleNamespace(text=body, raise_for_status=lambda: None)
        with patch.object(af, "request_with_retry", return_value=response):
            self.assertIsNone(af._fetch_via_jina(URL, 15))


if __name__ == "__main__":
    unittest.main()
